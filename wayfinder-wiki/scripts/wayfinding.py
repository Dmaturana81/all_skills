#!/usr/bin/env python3
"""Wayfinding maps stored inside a layered agent wiki (``wiki_*/``).

The wiki stands in for an issue tracker. Each effort lives in
``<wiki>/meta/wayfinding/<effort>/`` as one ``MAP.md`` plus one file per ticket
under ``tickets/``. This script provides the operations a tracker would give
natively: the frontier query, claiming, id allocation, generated indexes, and
a consistency check that keeps every map, ticket, and link findable.

Usage:
    wayfinding.py frontier <effort_dir>
    wayfinding.py next-id <effort_dir>
    wayfinding.py new <effort_dir> --type grilling --title "..." [--blocked-by 1,2] [--mode AFK]
    wayfinding.py claim <effort_dir> <ticket_id> <assignee> [--force]
    wayfinding.py index <wiki_dir>
    wayfinding.py check <wiki_dir>

Only the standard library is used. Frontmatter supports the YAML subset the
wiki uses: ``key: value``, ``key: [a, b]``, and ``key:`` followed by ``- item``
lines.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Set, Tuple, Union

Frontmatter = Dict[str, Union[str, List[str]]]
Sections = Dict[str, str]

MODES_BY_TYPE: Dict[str, Tuple[str, ...]] = {
    "research": ("AFK",),
    "prototype": ("HITL",),
    "grilling": ("HITL",),
    "task": ("AFK", "HITL"),
}
DEFAULT_MODE = {"research": "AFK", "prototype": "HITL", "grilling": "HITL", "task": "HITL"}
TICKET_STATUSES = ("open", "closed", "out-of-scope")
MAP_STATUSES = ("charting", "active", "cleared", "handed-off")
MAP_SECTIONS = ("Destination", "Notes", "Decisions so far", "Not yet specified", "Out of scope")
GENERATED_BANNER = "<!-- generated by wayfinding.py index; do not edit by hand -->"
TICKET_FILE_RE = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")
LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
FENCE_RE = re.compile(r"^```.*?^```", re.DOTALL | re.MULTILINE)


class WayfindingError(Exception):
    """Raised when a wayfinding operation cannot proceed safely."""


# --------------------------------------------------------------------------- parsing


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_frontmatter(block: str) -> Frontmatter:
    """Parse the wiki's YAML frontmatter subset.

    Args:
        block: Text between the opening and closing ``---`` lines.

    Returns:
        Mapping of keys to a string or a list of strings. A bare ``key:`` is an
        empty list, which ``scalar`` reads as an empty string.

    Raises:
        WayfindingError: If a line is neither ``key: value`` nor a list item.
    """
    data: Frontmatter = {}
    list_key: Optional[str] = None
    for raw in block.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("- ") and list_key is not None:
            items = data[list_key]
            assert isinstance(items, list)
            items.append(_unquote(stripped[2:]))
            continue
        key, sep, value = raw.partition(":")
        if not sep or not key.strip():
            raise WayfindingError(f"Unparseable frontmatter line: {raw!r}")
        value = value.split(" #", 1)[0].strip()
        list_key = None
        if not value:
            data[key.strip()] = []
            list_key = key.strip()
        elif value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            data[key.strip()] = [_unquote(v) for v in inner.split(",")] if inner else []
        else:
            data[key.strip()] = _unquote(value)
    return data


def split_document(text: str) -> Tuple[Frontmatter, str]:
    """Split a markdown document into frontmatter and body.

    Raises:
        WayfindingError: If the document has no closed frontmatter block.
    """
    if not text.startswith("---\n"):
        raise WayfindingError("Missing YAML frontmatter")
    end = text.find("\n---", 4)
    if end == -1:
        raise WayfindingError("Unclosed YAML frontmatter")
    body_start = text.find("\n", end + 4)
    body = text[body_start + 1 :] if body_start != -1 else ""
    return parse_frontmatter(text[4:end]), body


def scalar(fm: Frontmatter, key: str) -> str:
    """Return a frontmatter value as a string (empty if missing or a bare key)."""
    value = fm.get(key, "")
    return value if isinstance(value, str) else ""


def listing(fm: Frontmatter, key: str) -> List[str]:
    """Return a frontmatter value as a list (a scalar becomes a one-item list)."""
    value = fm.get(key, [])
    if isinstance(value, list):
        return [v for v in value if v]
    return [value] if value else []


def split_sections(body: str) -> Tuple[str, Sections]:
    """Return the H1 title and a mapping of ``## Heading`` to section text."""
    title = ""
    sections: Sections = {}
    current: Optional[str] = None
    lines: List[str] = []
    for line in body.splitlines():
        if line.startswith("# ") and not title and current is None:
            title = line[2:].strip()
        elif line.startswith("## "):
            if current is not None:
                sections[current] = "\n".join(lines).strip()
            current, lines = line[3:].strip(), []
        elif current is not None:
            lines.append(line)
    if current is not None:
        sections[current] = "\n".join(lines).strip()
    return title, sections


def meaningful(text: str) -> str:
    """Strip HTML comments and whitespace, leaving only authored content."""
    return COMMENT_RE.sub("", text).strip()


# --------------------------------------------------------------------------- model


@dataclass(frozen=True)
class Ticket:
    """One decision ticket: a file under ``<effort>/tickets/``."""

    path: Path
    id: int
    title: str
    type: str
    mode: str
    status: str
    assignee: str
    blocked_by: Tuple[int, ...]
    frontmatter: Frontmatter = field(compare=False, repr=False)
    sections: Sections = field(compare=False, repr=False)

    @property
    def label(self) -> str:
        return f"{self.id:04d}"

    @property
    def settled(self) -> bool:
        """Closed or ruled out of scope; either way it no longer blocks."""
        return self.status in ("closed", "out-of-scope")


@dataclass
class Effort:
    """One wayfinding map and its tickets."""

    root: Path
    title: str
    frontmatter: Frontmatter
    sections: Sections
    map_text: str
    tickets: List[Ticket]

    @property
    def slug(self) -> str:
        return self.root.name

    @property
    def status(self) -> str:
        return scalar(self.frontmatter, "status")

    def by_id(self) -> Dict[int, Ticket]:
        return {t.id: t for t in self.tickets}


def _parse_id(raw: str, path: Path) -> int:
    try:
        return int(raw)
    except ValueError as exc:
        raise WayfindingError(f"{path.name}: id {raw!r} is not a number") from exc


def load_ticket(path: Path) -> Ticket:
    """Load one ticket file.

    Raises:
        WayfindingError: If frontmatter is missing or ids are not numeric.
    """
    fm, body = split_document(path.read_text(encoding="utf-8"))
    title, sections = split_sections(body)
    return Ticket(
        path=path,
        id=_parse_id(scalar(fm, "id"), path),
        title=title or path.stem,
        type=scalar(fm, "type"),
        mode=scalar(fm, "mode"),
        status=scalar(fm, "status"),
        assignee=scalar(fm, "assignee"),
        blocked_by=tuple(_parse_id(b, path) for b in listing(fm, "blocked_by")),
        frontmatter=fm,
        sections=sections,
    )


def load_effort(effort_dir: Path) -> Tuple[Effort, List[str]]:
    """Load a map and every ticket it owns, collecting per-file load errors.

    Raises:
        WayfindingError: If ``MAP.md`` itself is missing or unparseable.
    """
    map_path = effort_dir / "MAP.md"
    if not map_path.is_file():
        raise WayfindingError(f"{effort_dir}: no MAP.md")
    map_text = map_path.read_text(encoding="utf-8")
    fm, body = split_document(map_text)
    title, sections = split_sections(body)
    tickets: List[Ticket] = []
    errors: List[str] = []
    tickets_dir = effort_dir / "tickets"
    for path in sorted(tickets_dir.glob("*.md")) if tickets_dir.is_dir() else []:
        if path.name == "README.md":
            continue
        try:
            tickets.append(load_ticket(path))
        except WayfindingError as exc:
            errors.append(f"{_rel(path, effort_dir)}: {exc}")
    tickets.sort(key=lambda t: t.id)
    effort = Effort(effort_dir, title or effort_dir.name, fm, sections, map_text, tickets)
    return effort, errors


def _rel(path: Path, base: Path) -> str:
    try:
        return str(path.relative_to(base))
    except ValueError:
        return str(path)


# --------------------------------------------------------------------------- queries


def frontier(tickets: Sequence[Ticket]) -> List[Ticket]:
    """Open, unclaimed tickets whose blockers are all settled, in id order."""
    settled = {t.id for t in tickets if t.settled}
    return [
        t
        for t in sorted(tickets, key=lambda t: t.id)
        if t.status == "open" and not t.assignee and all(b in settled for b in t.blocked_by)
    ]


def next_id(effort_dir: Path) -> int:
    """Return the next free ticket id for an effort (1 when there are none)."""
    tickets_dir = effort_dir / "tickets"
    ids = [
        int(m.group(1))
        for p in (tickets_dir.glob("*.md") if tickets_dir.is_dir() else [])
        if (m := TICKET_FILE_RE.match(p.name))
    ]
    return max(ids, default=0) + 1


def slugify(title: str) -> str:
    """Turn a ticket title into a filename slug."""
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug[:60].rstrip("-") or "ticket"


# --------------------------------------------------------------------------- mutations


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, path)


def new_ticket(
    effort_dir: Path,
    ticket_type: str,
    title: str,
    blocked_by: Sequence[int] = (),
    mode: Optional[str] = None,
) -> Path:
    """Create a ticket file with the next free id and an empty question.

    Args:
        effort_dir: The effort folder that holds ``MAP.md``.
        ticket_type: One of ``research``, ``prototype``, ``grilling``, ``task``.
        title: The ticket's name, written as its H1.
        blocked_by: Ids of existing tickets that block this one.
        mode: ``AFK`` or ``HITL``; defaults by type.

    Returns:
        Path of the created file.

    Raises:
        WayfindingError: On an unknown type, an invalid mode, or an unknown blocker.
    """
    if ticket_type not in MODES_BY_TYPE:
        raise WayfindingError(f"Unknown ticket type {ticket_type!r}")
    mode = mode or DEFAULT_MODE[ticket_type]
    if mode not in MODES_BY_TYPE[ticket_type]:
        raise WayfindingError(f"A {ticket_type} ticket cannot be {mode}")
    effort, _ = load_effort(effort_dir)
    unknown = set(blocked_by) - set(effort.by_id())
    if unknown:
        raise WayfindingError(f"Unknown blocker id(s): {sorted(unknown)}")
    ticket_id = next_id(effort_dir)
    path = effort_dir / "tickets" / f"{ticket_id:04d}-{slugify(title)}.md"
    blockers = ", ".join(f'"{b:04d}"' for b in blocked_by)
    _atomic_write(path, _ticket_template(effort.slug, ticket_id, title, ticket_type, mode, blockers))
    return path


def _ticket_template(slug: str, ticket_id: int, title: str, ticket_type: str, mode: str, blockers: str) -> str:
    return (
        "---\n"
        "layer: meta\n"
        "kind: wayfinder-ticket\n"
        f"effort: {slug}\n"
        f'id: "{ticket_id:04d}"\n'
        f"type: {ticket_type}\n"
        f"mode: {mode}\n"
        "status: open\n"
        "assignee:\n"
        f"blocked_by: [{blockers}]\n"
        "domains: []\n"
        "read_when: []\n"
        "parent: ../MAP.md\n"
        "---\n\n"
        f"# {title}\n\n"
        "## Question\n\n"
        "<!-- the decision or investigation this ticket resolves -->\n"
    )


def claim(effort_dir: Path, ticket_id: int, assignee: str, force: bool = False) -> Ticket:
    """Claim a ticket by writing its ``assignee`` before any work starts.

    Raises:
        WayfindingError: If the ticket is missing, settled, claimed by someone
            else, or still blocked (unless ``force``).
    """
    effort, _ = load_effort(effort_dir)
    ticket = effort.by_id().get(ticket_id)
    if ticket is None:
        raise WayfindingError(f"No ticket {ticket_id:04d} in {effort.slug}")
    if ticket.status != "open":
        raise WayfindingError(f"{ticket.title!r} is {ticket.status}, not open")
    if ticket.assignee and ticket.assignee != assignee:
        raise WayfindingError(f"{ticket.title!r} is already claimed by {ticket.assignee}")
    if not force and ticket not in frontier(effort.tickets) and not ticket.assignee:
        raise WayfindingError(f"{ticket.title!r} is still blocked; pass --force to claim anyway")
    text = ticket.path.read_text(encoding="utf-8")
    _atomic_write(ticket.path, _set_frontmatter_key(text, "assignee", assignee))
    return load_ticket(ticket.path)


def _set_frontmatter_key(text: str, key: str, value: str) -> str:
    end = text.find("\n---", 4)
    head, tail = text[:end], text[end:]
    pattern = re.compile(rf"^{re.escape(key)}:.*$", re.MULTILINE)
    if pattern.search(head):
        head = pattern.sub(f"{key}: {value}", head, count=1)
    else:
        head = f"{head}\n{key}: {value}"
    return head + tail


# --------------------------------------------------------------------------- indexes


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _gist(section: str, limit: int = 120) -> str:
    for line in meaningful(section).splitlines():
        line = line.strip().lstrip("-* ").strip()
        if line:
            return _cell(line if len(line) <= limit else line[: limit - 1] + "…")
    return "—"


def render_ticket_index(effort: Effort) -> str:
    """Render ``<effort>/tickets/README.md``: the frontier and every ticket."""
    by_id = effort.by_id()
    front = frontier(effort.tickets)
    lines = [
        "---",
        "layer: meta",
        "kind: wayfinder-ticket-index",
        f"effort: {effort.slug}",
        f"read_when: [frontier, tickets, {effort.slug}]",
        "parent: ../MAP.md",
        "---",
        "",
        GENERATED_BANNER,
        "",
        f"# Tickets: {effort.title}",
        "",
        "## Frontier",
        "",
    ]
    if front:
        lines += ["| Ticket | Type | Mode |", "|--------|------|------|"]
        lines += [f"| [{_cell(t.title)}]({t.path.name}) | {t.type} | {t.mode} |" for t in front]
    else:
        lines.append("_Empty: nothing is open, unblocked, and unclaimed._")
    lines += ["", "## All tickets", ""]
    if not effort.tickets:
        lines.append("_No tickets yet._")
        return "\n".join(lines) + "\n"
    lines += [
        "| Ticket | Type | Mode | Status | Claimed by | Blocked by |",
        "|--------|------|------|--------|------------|------------|",
    ]
    for t in effort.tickets:
        blockers = ", ".join(
            f"[{_cell(by_id[b].title)}]({by_id[b].path.name})" if b in by_id else f"missing {b:04d}"
            for b in t.blocked_by
        )
        lines.append(
            f"| [{_cell(t.title)}]({t.path.name}) | {t.type} | {t.mode} | {t.status} "
            f"| {_cell(t.assignee) or '—'} | {blockers or '—'} |"
        )
    return "\n".join(lines) + "\n"


def render_wayfinding_index(efforts: Sequence[Effort]) -> str:
    """Render ``meta/wayfinding/INDEX.md``: one row per map."""
    lines = [
        "---",
        "layer: meta",
        "kind: wayfinder-index",
        "scope: every wayfinding map in this wiki",
        "read_when: [wayfinding, wayfinder, map, roadmap, planning, frontier, effort]",
        "parent: ../INDEX.md",
        "---",
        "",
        GENERATED_BANNER,
        "",
        "# Wayfinding maps",
        "",
    ]
    if not efforts:
        return "\n".join(lines + ["_No maps yet._"]) + "\n"
    lines += [
        "| Map | Status | Destination | Frontier | Open | Settled |",
        "|-----|--------|-------------|----------|------|---------|",
    ]
    for e in efforts:
        open_count = sum(1 for t in e.tickets if t.status == "open")
        lines.append(
            f"| [{_cell(e.title)}]({e.slug}/MAP.md) | {e.status or '—'} "
            f"| {_gist(e.sections.get('Destination', ''))} | {len(frontier(e.tickets))} "
            f"| {open_count} | {len(e.tickets) - open_count} |"
        )
    return "\n".join(lines) + "\n"


def wayfinding_root(wiki_dir: Path) -> Path:
    return wiki_dir / "meta" / "wayfinding"


def effort_dirs(wiki_dir: Path) -> List[Path]:
    root = wayfinding_root(wiki_dir)
    return sorted(p for p in root.iterdir() if p.is_dir()) if root.is_dir() else []


def write_indexes(wiki_dir: Path) -> List[Path]:
    """Regenerate every ticket index and the wayfinding index.

    Returns:
        Paths that were written.
    """
    efforts = [load_effort(d)[0] for d in effort_dirs(wiki_dir) if (d / "MAP.md").is_file()]
    written: List[Path] = []
    for effort in efforts:
        path = effort.root / "tickets" / "README.md"
        _atomic_write(path, render_ticket_index(effort))
        written.append(path)
    index = wayfinding_root(wiki_dir) / "INDEX.md"
    _atomic_write(index, render_wayfinding_index(efforts))
    written.append(index)
    return written


# --------------------------------------------------------------------------- checks


def broken_links(path: Path, text: str) -> List[str]:
    """Relative markdown links in ``text`` that do not resolve from ``path``."""
    scan = FENCE_RE.sub("", COMMENT_RE.sub("", text))
    missing = []
    for target in LINK_RE.findall(scan):
        if re.match(r"^[a-z]+:", target) or target.startswith("#"):
            continue
        local = target.split("#", 1)[0]
        if local and not (path.parent / local).exists():
            missing.append(target)
    return missing


def _linked_tickets(section: str) -> Set[str]:
    return {Path(t.split("#", 1)[0]).name for t in LINK_RE.findall(meaningful(section)) if "tickets/" in t}


def check_map(effort: Effort) -> List[str]:
    """Structural and consistency errors for one map."""
    errors: List[str] = []
    fm, name = effort.frontmatter, "MAP.md"
    if scalar(fm, "kind") != "wayfinder-map":
        errors.append(f"{name}: kind must be wayfinder-map")
    if scalar(fm, "effort") != effort.slug:
        errors.append(f"{name}: effort must equal folder name {effort.slug!r}")
    if effort.status not in MAP_STATUSES:
        errors.append(f"{name}: status must be one of {', '.join(MAP_STATUSES)}")
    present = [s for s in effort.sections if s in MAP_SECTIONS]
    if present != list(MAP_SECTIONS):
        errors.append(f"{name}: sections must be, in order: {', '.join(MAP_SECTIONS)}")
    if not meaningful(effort.sections.get("Destination", "")):
        errors.append(f"{name}: Destination is empty")
    errors += _check_map_ledger(effort)
    errors += _check_map_status(effort)
    return errors


def _check_map_ledger(effort: Effort) -> List[str]:
    errors: List[str] = []
    decisions = _linked_tickets(effort.sections.get("Decisions so far", ""))
    out_of_scope = _linked_tickets(effort.sections.get("Out of scope", ""))
    for t in effort.tickets:
        name = t.path.name
        if t.status == "closed" and name not in decisions:
            errors.append(f"MAP.md: closed ticket {t.title!r} missing from Decisions so far")
        if t.status != "closed" and name in decisions:
            errors.append(f"MAP.md: Decisions so far lists {t.title!r}, which is {t.status}")
        if t.status == "out-of-scope" and name not in out_of_scope:
            errors.append(f"MAP.md: out-of-scope ticket {t.title!r} missing from Out of scope")
        if t.status != "out-of-scope" and name in out_of_scope:
            errors.append(f"MAP.md: Out of scope lists {t.title!r}, which is {t.status}")
    return errors


def _check_map_status(effort: Effort) -> List[str]:
    errors: List[str] = []
    if effort.status in ("cleared", "handed-off"):
        if any(t.status == "open" for t in effort.tickets):
            errors.append(f"MAP.md: status {effort.status} but tickets are still open")
        if meaningful(effort.sections.get("Not yet specified", "")):
            errors.append(f"MAP.md: status {effort.status} but Not yet specified still has fog")
    if effort.status == "handed-off":
        handoff = scalar(effort.frontmatter, "handoff")
        if not handoff or not (effort.root / handoff).exists():
            errors.append("MAP.md: handed-off maps need a handoff: path that exists")
    return errors


def check_tickets(effort: Effort) -> List[str]:
    """Per-ticket errors plus blocking-graph errors for one effort."""
    errors: List[str] = []
    seen: Dict[int, Path] = {}
    for t in effort.tickets:
        prefix = f"tickets/{t.path.name}"
        match = TICKET_FILE_RE.match(t.path.name)
        if not match or int(match.group(1)) != t.id:
            errors.append(f"{prefix}: filename must be {t.label}-<slug>.md")
        if t.id in seen:
            errors.append(f"{prefix}: duplicate id {t.label} (also {seen[t.id].name})")
        seen[t.id] = t.path
        errors += [f"{prefix}: {e}" for e in _ticket_field_errors(effort, t)]
    errors += _cycle_errors(effort.tickets)
    return errors


def _ticket_field_errors(effort: Effort, t: Ticket) -> List[str]:
    errors: List[str] = []
    if scalar(t.frontmatter, "kind") != "wayfinder-ticket":
        errors.append("kind must be wayfinder-ticket")
    if scalar(t.frontmatter, "effort") != effort.slug:
        errors.append(f"effort must be {effort.slug!r}")
    if t.type not in MODES_BY_TYPE:
        errors.append(f"type must be one of {', '.join(MODES_BY_TYPE)}")
    elif t.mode not in MODES_BY_TYPE[t.type]:
        errors.append(f"a {t.type} ticket must be {' or '.join(MODES_BY_TYPE[t.type])}")
    if t.status not in TICKET_STATUSES:
        errors.append(f"status must be one of {', '.join(TICKET_STATUSES)}")
    if not meaningful(t.sections.get("Question", "")):
        errors.append("## Question is empty")
    if t.settled and not meaningful(t.sections.get("Resolution", "")):
        errors.append(f"{t.status} tickets need a ## Resolution")
    known = effort.by_id()
    for b in t.blocked_by:
        if b == t.id:
            errors.append("blocks itself")
        elif b not in known:
            errors.append(f"blocked_by {b:04d} does not exist")
    return errors


def _cycle_errors(tickets: Sequence[Ticket]) -> List[str]:
    graph = {t.id: [b for b in t.blocked_by if b != t.id] for t in tickets}
    state: Dict[int, int] = {}
    cycles: List[str] = []

    def visit(node: int, trail: List[int]) -> None:
        state[node] = 1
        for nxt in graph.get(node, []):
            if state.get(nxt) == 1:
                loop = trail[trail.index(nxt) :] + [nxt] if nxt in trail else [node, nxt]
                cycles.append("blocking cycle: " + " -> ".join(f"{n:04d}" for n in loop))
            elif nxt in graph and not state.get(nxt):
                visit(nxt, trail + [nxt])
        state[node] = 2

    for node in graph:
        if not state.get(node):
            visit(node, [node])
    return cycles


def check_effort(effort: Effort) -> List[str]:
    """Every error for one effort: map, tickets, links, and index freshness."""
    errors = check_map(effort) + check_tickets(effort)
    errors += [f"MAP.md: broken link {l}" for l in broken_links(effort.root / "MAP.md", effort.map_text)]
    for t in effort.tickets:
        text = t.path.read_text(encoding="utf-8")
        errors += [f"tickets/{t.path.name}: broken link {l}" for l in broken_links(t.path, text)]
    index = effort.root / "tickets" / "README.md"
    if not index.is_file() or index.read_text(encoding="utf-8") != render_ticket_index(effort):
        errors.append("tickets/README.md is missing or stale; run `wayfinding.py index`")
    return [f"{effort.slug}/{e}" for e in errors]


def check_wiki(wiki_dir: Path) -> Tuple[List[str], int, int]:
    """Check every map in a wiki.

    Returns:
        Errors, number of maps, and number of tickets.
    """
    root = wayfinding_root(wiki_dir)
    if not root.is_dir():
        return [], 0, 0
    errors: List[str] = []
    efforts: List[Effort] = []
    for d in effort_dirs(wiki_dir):
        try:
            effort, load_errors = load_effort(d)
        except WayfindingError as exc:
            errors.append(f"{d.name}: {exc}")
            continue
        efforts.append(effort)
        errors += [f"{d.name}/{e}" for e in load_errors] + check_effort(effort)
    index = root / "INDEX.md"
    if not index.is_file() or index.read_text(encoding="utf-8") != render_wayfinding_index(efforts):
        errors.append("meta/wayfinding/INDEX.md is missing or stale; run `wayfinding.py index`")
    return errors, len(efforts), sum(len(e.tickets) for e in efforts)


# --------------------------------------------------------------------------- CLI


def _cmd_frontier(args: argparse.Namespace) -> int:
    effort, _ = load_effort(Path(args.effort_dir))
    tickets = frontier(effort.tickets)
    if not tickets:
        print(f"Frontier empty for {effort.title!r}.")
    for t in tickets:
        print(f"{t.label}  {t.type:<9} {t.mode:<4}  {t.title}  ({_rel(t.path, effort.root)})")
    return 0


def _cmd_next_id(args: argparse.Namespace) -> int:
    print(f"{next_id(Path(args.effort_dir)):04d}")
    return 0


def _cmd_index(args: argparse.Namespace) -> int:
    for path in write_indexes(Path(args.wiki_dir)):
        print(f"wrote {path}")
    return 0


def _cmd_new(args: argparse.Namespace) -> int:
    blockers = [int(b) for b in args.blocked_by.split(",") if b.strip()] if args.blocked_by else []
    print(new_ticket(Path(args.effort_dir), args.type, args.title, blockers, args.mode))
    return 0


def _cmd_claim(args: argparse.Namespace) -> int:
    ticket = claim(Path(args.effort_dir), int(args.ticket_id), args.assignee, args.force)
    print(f"Claimed {ticket.title!r} for {ticket.assignee} ({ticket.path})")
    return 0


def _cmd_check(args: argparse.Namespace) -> int:
    errors, maps, tickets = check_wiki(Path(args.wiki_dir))
    if errors:
        print("Wayfinding check FAILED:")
        print("\n".join(f"  - {e}" for e in errors))
        return 1
    print(f"Wayfinding check OK: {maps} map(s), {tickets} ticket(s)")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Wayfinding maps inside a layered agent wiki.")
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("frontier", help="List open, unblocked, unclaimed tickets")
    p.add_argument("effort_dir")
    p.set_defaults(func=_cmd_frontier)
    p = sub.add_parser("next-id", help="Print the next free ticket id")
    p.add_argument("effort_dir")
    p.set_defaults(func=_cmd_next_id)
    p = sub.add_parser("new", help="Create a ticket with the next free id")
    p.add_argument("effort_dir")
    p.add_argument("--type", required=True, choices=sorted(MODES_BY_TYPE))
    p.add_argument("--title", required=True)
    p.add_argument("--blocked-by", default="", help="Comma-separated blocker ids")
    p.add_argument("--mode", choices=("AFK", "HITL"))
    p.set_defaults(func=_cmd_new)
    p = sub.add_parser("claim", help="Assign a ticket before working it")
    p.add_argument("effort_dir")
    p.add_argument("ticket_id")
    p.add_argument("assignee")
    p.add_argument("--force", action="store_true", help="Claim even if still blocked")
    p.set_defaults(func=_cmd_claim)
    p = sub.add_parser("index", help="Regenerate ticket indexes and meta/wayfinding/INDEX.md")
    p.add_argument("wiki_dir")
    p.set_defaults(func=_cmd_index)
    p = sub.add_parser("check", help="Validate every map, ticket, link, and index")
    p.add_argument("wiki_dir")
    p.set_defaults(func=_cmd_check)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args) or 0)
    except WayfindingError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
